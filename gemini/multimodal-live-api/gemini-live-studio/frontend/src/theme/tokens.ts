/**
 * Reads a colour token from the computed style of `el` (so it follows the
 * active theme) and returns it as an `rgb()`/`rgba()` string for canvas use.
 */
export function readColorToken(
  el: Element,
  token: ColorToken,
  alpha = 1,
): string {
  return colorTokenReader(el)(token, alpha);
}

/**
 * Like `readColorToken`, but resolves the computed style once and returns a
 * reader, for code that needs many colours per frame (canvas render loops).
 */
export function colorTokenReader(
  el: Element,
): (token: ColorToken, alpha?: number) => string {
  const style = getComputedStyle(el);
  return (token, alpha = 1) => {
    const channels = style.getPropertyValue(colorVar(token)).trim();
    return `rgb(${channels || hexToChannels(lightColors[token])} / ${alpha})`;
  };
}

/** Applies a theme to the document root. */
export function setTheme(
  theme: GaTheme,
  root: HTMLElement = document.documentElement,
): void {
  root.dataset.theme = theme;
}
