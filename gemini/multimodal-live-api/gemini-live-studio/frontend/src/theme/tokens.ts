/**
 * The single source of truth for Gemini Live Studio design tokens.
 *
 * - `tokens.css` (generated by `npm run tokens`, checked by a unit test)
 *   turns these into `--ga-*` CSS custom properties per theme.
 * - `tailwind.config.ts` maps every colour to `rgb(var(--ga-color-*) / <alpha>)`,
 *   so utility classes such as `bg-primary/10` keep working and follow the
 *   active theme.
 * - Canvas / JS code reads colours at runtime with `readColorToken()`.
 *
 * Themes are selected with `data-theme="light" | "dark" | "system"` on
 * `<html>` (or any ancestor). With no attribute the light theme applies.
 *
 * This module must stay free of side effects and imports so that Node scripts
 * and the Tailwind config can load it directly.
 */

