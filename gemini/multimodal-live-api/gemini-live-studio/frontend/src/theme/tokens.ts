export type GaTheme = 'light' | 'dark' | 'system';

/** CSS custom property name for a colour token. */
export function colorVar(token: ColorToken): string {
  return `--ga-color-${token}`;
}

/** "#4285F4" -> "66 133 244" (space-separated channels for rgb(var() / a)). */
export function hexToChannels(hex: string): string {
  const h = hex.replace('#', '');
  const full = h.length === 3 ? [...h].map((c) => c + c).join('') : h;
  const n = Number.parseInt(full, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
}

function declarations(
  colors: Record<ColorToken, string>,
  indent: string,
): string {
  return (Object.keys(colors) as ColorToken[])
    .map((k) => `${indent}${colorVar(k)}: ${hexToChannels(colors[k])};`)
    .join('\n');
}

